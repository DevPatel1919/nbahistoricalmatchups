"""
audit_prediction_inputs.py

Verifies that every column required by the active model release can be built
from team_season_profiles_extended.csv, and documents the input contract.

Run from repo root:
    python src/models/audit_prediction_inputs.py

Outputs:
    models/experiments/prediction_input_contract.md
"""

from pathlib import Path

import pandas as pd

_REPO = Path(__file__).resolve().parents[2]

from src.models.model_config import (
    PROFILES_PATH,
    AUDIT_CONTRACT_REPORT,
)
from src.models.release import Release, load_active_release

# Primary output: reports/audits/
OUTPUT_PATH = AUDIT_CONTRACT_REPORT
# Secondary output: models/experiments/ (keep for historical reference)
SECONDARY_OUTPUT_PATH = _REPO / "models" / "experiments" / "prediction_input_contract.md"


def _source_col(model_col: str) -> str | None:
    """Return the base source column name for a model column, or None for _diff."""
    if model_col.endswith("_diff"):
        return None
    if model_col.startswith("home_"):
        return model_col[5:]
    if model_col.startswith("away_"):
        return model_col[5:]
    return model_col


def audit(model_cols: list[str], profile_cols: set[str]) -> dict:
    """
    Returns a dict with:
        required_sources  - all base stat names the model needs from the CSV
        present           - sources found in CSV
        missing           - sources NOT found in CSV
        diff_cols         - _diff model columns (derived, not directly from CSV)
        home_cols         - home_ model columns
        away_cols         - away_ model columns
    """
    required_sources: set[str] = set()
    home_cols, away_cols, diff_cols = [], [], []

    for col in model_cols:
        if col.endswith("_diff"):
            diff_cols.append(col)
            base = col[:-5]
            required_sources.add(base)
        elif col.startswith("home_"):
            home_cols.append(col)
            required_sources.add(col[5:])
        elif col.startswith("away_"):
            away_cols.append(col)
            required_sources.add(col[5:])

    present = sorted(s for s in required_sources if s in profile_cols)
    missing = sorted(s for s in required_sources if s not in profile_cols)

    return {
        "required_sources": sorted(required_sources),
        "present":          present,
        "missing":          missing,
        "home_cols":        home_cols,
        "away_cols":        away_cols,
        "diff_cols":        diff_cols,
    }


def write_report(model_cols: list[str], result: dict, profile_df: pd.DataFrame, release: Release) -> None:
    seasons   = sorted(profile_df["season"].unique())
    num_teams = profile_df["team_id"].nunique()
    num_rows  = len(profile_df)

    lines = [
        "# Prediction Input Contract",
        "",
        "Generated by `src/models/audit_prediction_inputs.py`.",
        "",
        "## Overview",
        "",
        "The production app accepts two team-season selections and returns a matchup prediction.",
        "This document defines the full input pipeline from user selection to model inference.",
        "",
        "## Flow",
        "",
        "```",
        "User selects Team A (name + season)  +  Team B (name + season)",
        "         |",
        "         v",
        "find_team_profile()  -->  looks up one row per team from team_season_profiles_extended.csv",
        "         |",
        "         v",
        "build_model_input()  -->  constructs home_, away_, and _diff features",
        "         |",
        "         v",
        f"Filter + order by release columns.json  ({len(model_cols)} columns)",
        "         |",
        "         v",
        f"classifier.pkl  ({release.classifier_name}, release {release.version})",
        f"regressor.pkl   ({release.regressor_name})",
        "         |",
        "         v",
        "Return: winner, win probability, projected margin",
        "```",
        "",
        "## Source Table",
        "",
        f"**File:** `data/processed/team_season_profiles_extended.csv`",
        f"**Rows:** {num_rows} team-seasons",
        f"**Teams:** {num_teams}",
        f"**Seasons:** {min(seasons)} - {max(seasons)} ({len(seasons)} seasons)",
        f"**Columns:** {len(profile_df.columns)}",
        "",
        "## Model Column Summary",
        "",
        f"| Type | Count |",
        f"| ---- | ----- |",
        f"| Total model columns | {len(model_cols)} |",
        f"| home_ (Team A direct stats) | {len(result['home_cols'])} |",
        f"| away_ (Team B direct stats) | {len(result['away_cols'])} |",
        f"| _diff (home - away computed) | {len(result['diff_cols'])} |",
        f"| Unique source fields required | {len(result['required_sources'])} |",
        f"| Source fields found in CSV | {len(result['present'])} |",
        f"| Source fields MISSING from CSV | {len(result['missing'])} |",
        "",
    ]

    if result["missing"]:
        lines += [
            "## MISSING Source Fields",
            "",
            "The following base stat names are required by the model but NOT found in the profile CSV.",
            "These must be added to the CSV before production use.",
            "",
        ]
        for m in result["missing"]:
            lines.append(f"- `{m}`")
        lines.append("")
    else:
        lines += [
            "## Source Field Coverage",
            "",
            "All required source fields are present in `team_season_profiles_extended.csv`. No gaps.",
            "",
        ]

    lines += [
        "## Required Source Fields",
        "",
        "These are the base stat column names that must exist in `team_season_profiles_extended.csv` "
        "for the model to function. Each is used to populate both the `home_` and `away_` sides.",
        "",
        "| Source Field | In CSV? |",
        "| ------------ | ------- |",
    ]
    for s in result["required_sources"]:
        present = "yes" if s in set(result["present"]) else "**MISSING**"
        lines.append(f"| `{s}` | {present} |")
    lines.append("")

    lines += [
        f"## All {len(model_cols)} Model Columns",
        "",
        "Listed in exact order expected by the model. `_diff` columns are computed; "
        "all others are sourced directly from the profile CSV.",
        "",
        "| # | Column | Source |",
        "| - | ------ | ------ |",
    ]
    for i, col in enumerate(model_cols, 1):
        if col.endswith("_diff"):
            src = f"computed: `home_{col[:-5]}` - `away_{col[:-5]}`"
        elif col.startswith("home_"):
            src = f"team_a[`{col[5:]}`]"
        elif col.startswith("away_"):
            src = f"team_b[`{col[5:]}`]"
        else:
            src = col
        lines.append(f"| {i} | `{col}` | {src} |")
    lines.append("")

    lines += [
        "## Non-Playoff Teams",
        "",
        "The current best model was trained on **playoff games only** (`playoffs_only` dataset filter).",
        "For teams that did not make the playoffs, playoff context features are filled with `0` in the profile CSV.",
        "",
        "**Effect on predictions:**",
        "- `playoff_win_pct_diff` (the model's strongest feature, coefficient 1.19) will be 0 for non-playoff teams.",
        "- The model can still run and return a probability, but the prediction is less reliable.",
        "- `predict_matchup()` sets `prediction_mode = 'playoff_context_model_extrapolated'` and adds a `warnings` entry.",
        "",
        "**Recommendation:** Surface the warning in the UI when `prediction_mode != 'playoff_context_model'`.",
        "",
        "## Team Name Matching",
        "",
        "Team lookup in `predict_matchup()` accepts case-insensitive:",
        "- Full name: `'Golden State Warriors'`",
        "- City only: `'Golden State'`",
        "- Team name only: `'Warriors'`",
        "- Partial match: `'warrior'` (substring match on full name)",
        "",
        "If the query matches more than one row, a `ValueError` is raised with the list of matches.",
        "If no row is found, a `ValueError` is raised with the list of valid teams for that season.",
        "",
        "## Model Metadata",
        "",
        "| Field | Value |",
        "| ----- | ----- |",
        f"| Release | {release.version} |",
        f"| Purpose | {release.purpose} |",
        f"| Classification model | {release.classifier_name} |",
        f"| Regression model | {release.regressor_name} |",
        f"| Trained through season | {release.manifest['trainedThroughSeason']} |",
        f"| Source | {release.manifest['source']} |",
        "| Published accuracy | none; see the release's metrics.json |",
        "",
    ]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = "\n".join(lines)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(content)

    # Mirror copy to models/experiments/ for backward compatibility
    SECONDARY_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(SECONDARY_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(content)


def main() -> None:
    release    = load_active_release()
    model_cols = release.columns

    profile_df   = pd.read_csv(PROFILES_PATH)
    profile_cols = set(profile_df.columns)

    result = audit(model_cols, profile_cols)

    write_report(model_cols, result, profile_df, release)

    # Terminal output
    print("=" * 60)
    print("PREDICTION INPUT CONTRACT AUDIT")
    print("=" * 60)
    print(f"Model columns required:        {len(model_cols)}")
    print(f"  home_ columns:               {len(result['home_cols'])}")
    print(f"  away_ columns:               {len(result['away_cols'])}")
    print(f"  _diff columns (computed):    {len(result['diff_cols'])}")
    print(f"Unique source fields needed:   {len(result['required_sources'])}")
    print(f"Source fields in CSV:          {len(result['present'])}")
    print(f"Source fields MISSING:         {len(result['missing'])}")
    print()

    if result["missing"]:
        print("MISSING SOURCE FIELDS:")
        for m in result["missing"]:
            print(f"  - {m}")
    else:
        print("COVERAGE: All required source fields present in team_season_profiles_extended.csv.")

    print()
    print(f"Report saved to: {OUTPUT_PATH}")
    print(f"Mirror copy at:  {SECONDARY_OUTPUT_PATH}")
    print()

    # Quick sanity check: run a sample prediction
    try:
        from src.models.predict_matchup import predict_matchup
        r = predict_matchup("Golden State Warriors", 2017, "Cleveland Cavaliers", 2016)
        print("SAMPLE PREDICTION:")
        print(f"  {r['team_a']}  vs  {r['team_b']}")
        print(f"  Winner:  {r['predicted_winner']}")
        print(f"  Prob A:  {r['team_a_win_probability']:.1%}   Prob B:  {r['team_b_win_probability']:.1%}")
        print(f"  Margin:  {r['projected_margin_team_a']} pts  (positive = Team A wins by that)")
        print(f"  Mode:    {r['prediction_mode']}")
        if r["warnings"]:
            for w in r["warnings"]:
                print(f"  WARNING: {w}")
    except Exception as e:
        print(f"Sample prediction skipped (model files may not exist yet): {e}")


if __name__ == "__main__":
    main()

def stat_name_for(source_col: str) -> str:
    for name, (col, _digits) in MEAN_STATS.items():
        if col == source_col:
            return name
    raise ValueError("No MEAN_STATS entry reads " + source_col)


def validate_formulas(allowed_ids: set) -> tuple[str, dict]:
    """Compare every formula with the NBA's value per team-season, 1996-97 on."""
    nba = _read_team_games(STATS_PATH)
    nba = nba[(nba["season"] > EXTENDED_STATS_START) & nba["teamId"].isin(allowed_ids)]
    nba = nba[nba["gameType"].isin([GAME_TYPE_REGULAR, GAME_TYPE_PLAYOFF])]
    est = compute_box_score_advanced(nba)

    # Possession scale: fit on early seasons, check on later ones
    g = with_opponent_box(nba)
    raw = estimate_possessions(g, scale=1.0)
    fit = g["season"] <= SCALE_FIT_LAST
    fitted_scale = float(g.loc[fit, "possessions"].sum() / raw[fit].sum())
    poss_rows = []
    for label, scale in (("Standard formula (scale 1.0)", 1.0),
                         ("Fitted on " + str(EXTENDED_STATS_START + 1) + "-" + str(SCALE_FIT_LAST)
                          + " (scale " + fmt(fitted_scale, 4) + ")", fitted_scale),
                         ("As used (POSSESSION_SCALE " + str(POSSESSION_SCALE) + ")", POSSESSION_SCALE)):
        err = scale * raw - g["possessions"]
        held = ~fit
        poss_rows.append([label, fmt(err[fit].mean(), 2), fmt(err[held].mean(), 2),
                          fmt(err[held].abs().mean(), 2)])

    keys = ["teamId", "season", "gameType"]
    verdicts = {}
    rows = []
    for col in BOX_SCORE_FORMULAS:
        a = nba.groupby(keys)[col].mean()
        b = est.groupby(keys)[col].mean()
        for game_type in (GAME_TYPE_REGULAR, GAME_TYPE_PLAYOFF):
            if game_type == GAME_TYPE_PLAYOFF and col not in ("offensiveRating", "defensiveRating", "netRating", "trueShootingPercentage"):
                continue
            aa = a.xs(game_type, level="gameType")
            bb = b.xs(game_type, level="gameType")
            diff = (bb - aa).dropna()
            gap  = aa.quantile(0.8) - aa.quantile(0.5)
            if col in ("defensiveRating", "opponentEffectiveFieldGoalPercentage", "teamTurnoverPercentage",
                       "opponentFreeThrowAttemptRate", "opponentOffensiveReboundPercentage"):
                gap = aa.quantile(0.5) - aa.quantile(0.2)   # lower is better
            mae  = diff.abs().mean()
            share = mae / abs(gap) if gap else np.nan
            usable = bool(share < USABLE_ERROR_SHARE)
            prefix = "regular" if game_type == GAME_TYPE_REGULAR else "playoff"
            verdicts[col] = verdicts.get(col, True) and usable
            rows.append([
                prefix + "_" + stat_name_for(col),
                str(len(diff)),
                fmt(aa.mean(), 3), fmt(diff.mean(), 3), fmt(mae, 3), fmt(diff.abs().max(), 3),
                fmt(gap, 3), fmt(share * 100, 0) + "%", "yes" if usable else "**no**",
            ])

    text = "\n\n".join([
        "Possessions per team-game against the NBA's count (error = estimate - NBA). "
        "Fit period: seasons " + str(EXTENDED_STATS_START + 1) + "-" + str(SCALE_FIT_LAST)
        + "; held-out: " + str(SCALE_FIT_LAST + 1) + " on.",
        md_table(["Possession estimate", "Bias, fit seasons", "Bias, held-out", "Mean abs. error, held-out"], poss_rows),
        "Per team-season averages, " + str(EXTENDED_STATS_START + 1) + "-2026, formula minus NBA value. "
        "\"Avg-to-good gap\" is the distance between the 50th and 80th percentile team-season "
        "(20th and 50th where lower is better). A stat is usable when its mean absolute error "
        "is under " + str(int(USABLE_ERROR_SHARE * 100)) + "% of that gap. Stats marked **no** "
        "are left blank for seasons before 1996-97 (`UNMATCHED_FORMULA_COLS`).",
        md_table(["Profile stat", "Team-seasons", "NBA mean", "Bias", "Mean abs. error", "Max abs. error",
                  "Avg-to-good gap", "Error / gap", "Usable"], rows),
    ])
    failed = sorted(c for c, ok in verdicts.items() if not ok)
    if failed != sorted(UNMATCHED_FORMULA_COLS):
        raise ValueError("Formula verdicts changed: failing " + str(failed) + " but UNMATCHED_FORMULA_COLS is "
                         + str(sorted(UNMATCHED_FORMULA_COLS)) + ". Update the profile builder.")
    return text, verdicts



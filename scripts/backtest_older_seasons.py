def to_relative(values: pd.DataFrame, ref_seasons: pd.Series, ref: pd.DataFrame) -> pd.DataFrame:
    """Each PROBE_STATS column as a z-score against the league in ref_seasons."""
    out = values.copy()
    for stat in PROBE_STATS:
        mean = ref_seasons.map(ref[(stat, "mean")])
        std  = ref_seasons.map(ref[(stat, "std")]).where(lambda x: x > 0)
        out[stat] = (values[stat] - mean) / std
    return out


def probe_game_matrix(games: pd.DataFrame, ref=None) -> pd.DataFrame:
    """home_/away_/_diff probe features for real games; relative to the PREVIOUS season when ref is given."""
    sides = {}
    for side in ("home", "away"):
        v = games[[side + "_" + s for s in PROBE_STATS]].set_axis(PROBE_STATS, axis=1)
        sides[side] = to_relative(v, games["season"] - 1, ref) if ref is not None else v
    data = {}
    for stat in PROBE_STATS:
        data["home_" + stat] = sides["home"][stat].to_numpy()
        data["away_" + stat] = sides["away"][stat].to_numpy()
        data[stat + "_diff"] = data["home_" + stat] - data["away_" + stat]
    return pd.DataFrame(data)


def neutral_pairs(model, cols: list, profiles: pd.DataFrame, older_idx: np.ndarray, modern_idx: np.ndarray) -> np.ndarray:
    """Neutral P(older team wins) for every older x modern pair, as the export neutralises."""
    from scripts.export_static_site_data import build_base_stat_arrays, build_feature_chunk
    from src.models.release import parse_base_stats
    arrays = build_base_stat_arrays(profiles, parse_base_stats(cols))
    ii, jj = np.meshgrid(older_idx, modern_idx, indexing="ij")
    ii, jj = ii.ravel(), jj.ravel()
    win = list(model.classes_).index(1)
    p_ab = model.predict_proba(build_feature_chunk(ii, jj, arrays, cols))[:, win]
    p_ba = model.predict_proba(build_feature_chunk(jj, ii, arrays, cols))[:, win]
    return (p_ab + (1 - p_ba)) / 2


def pair_summary(label: str, p: np.ndarray, matched: np.ndarray) -> list:
    return [label, fmt(p.mean() * 100, 1) + "%", fmt((p > 0.5).mean() * 100, 1) + "%",
            fmt(p[matched].mean() * 100, 1) + "%"]


def era_probe_section(profiles: pd.DataFrame, older: pd.DataFrame, modern: pd.DataFrame, release) -> tuple[str, dict]:
    ref = profiles.groupby("season")[PROBE_STATS].agg(["mean", "std"])
    y_col = "home_win"
    train = modern[(modern["season"] >= PROBE_TRAIN[0]) & (modern["season"] <= PROBE_TRAIN[1])]
    evals = [
        ("1987-1997", older[(older["season"] >= PROBE_OLDER_PAIRS[0]) & (older["season"] <= PROBE_OLDER_PAIRS[1])]),
        ("2019-2021", modern[(modern["season"] >= 2019) & (modern["season"] <= 2021)]),
        ("2022-2026", modern[modern["season"] >= 2022]),
        ("2024-2026", modern[modern["season"] >= 2024]),
    ]

    # Neutral pairings between completed seasons (full-season profiles)
    prof = profiles.reset_index(drop=True)
    older_idx  = prof.index[(prof["season"] >= PROBE_OLDER_PAIRS[0]) & (prof["season"] <= PROBE_OLDER_PAIRS[1])].to_numpy()
    modern_idx = prof.index[(prof["season"] >= PROBE_MODERN_PAIRS[0]) & (prof["season"] <= PROBE_MODERN_PAIRS[1])].to_numpy()
    net = prof["regular_net_rating"].to_numpy()
    matched = (np.abs(net[older_idx][:, None] - net[modern_idx][None, :]) < 1.0).ravel()

    game_rows, pair_rows, key = [], [], {}
    for label, use_ref in (("Raw inputs", None), ("League-relative inputs", ref)):
        model = Pipeline([("imputer", SimpleImputer(strategy="median")), ("scaler", StandardScaler()),
                          ("clf", LogisticRegression(C=1.0, max_iter=3000))])
        model.fit(probe_game_matrix(train, use_ref), train[y_col])
        for eval_label, e in evals:
            p = model.predict_proba(probe_game_matrix(e, use_ref))[:, 1]
            scored = pd.DataFrame({"home_win": e[y_col].to_numpy(), "p_home": p,
                                   "home_regular_win_pct": e["home_regular_win_pct"].to_numpy(),
                                   "away_regular_win_pct": e["away_regular_win_pct"].to_numpy()})
            game_rows.append(metric_row(label + ", " + eval_label, scored)[:5])

        # A completed season is compared with its own league here (the served-profile
        # question Session 2 decides); training used the previous season.
        pair_prof = to_relative(prof, prof["season"], ref) if use_ref is not None else prof
        cols = list(probe_game_matrix(train.head(1)).columns)
        p = neutral_pairs(model, cols, pair_prof, older_idx, modern_idx)
        pair_rows.append(pair_summary("Probe, " + label.lower(), p, matched))
        key[label] = float(p[matched].mean())

    p = neutral_pairs(release.classifier, release.columns, prof, older_idx, modern_idx)
    pair_rows.insert(0, pair_summary("`" + release.version + "` (served)", p, matched))
    key[release.version] = float(p[matched].mean())

    text = "\n\n".join([
        "Two probe models, not releases: the same logistic regression on the same " + str(len(PROBE_STATS))
        + " regular-season stats (home, away and difference), trained on point-in-time games from "
        + str(PROBE_TRAIN[0]) + "-" + str(PROBE_TRAIN[1]) + ". \"Raw\" reads the stats as they are. "
        "\"League-relative\" reads each one as a z-score against the previous season's teams "
        "(the point-in-time rule; `_build_pool` in `train_model_experiments.py` does the same). "
        "1986 has no previous season, so these rows start in 1987. 2022 is almost missing from the "
        "profiles (2 team-seasons of 1 game each; see CONTRIBUTING.md), so 2023 is measured against "
        "a meaningless reference: the 2024-2026 rows show the relative probe without that defect.",
        "**Real games** (both teams always from the same season)\n\n"
        + md_table(["Model, seasons", "n", "Accuracy", "Log loss", "Brier"], game_rows),
        "**Cross-era pairings**: every " + str(PROBE_OLDER_PAIRS[0]) + "-" + str(PROBE_OLDER_PAIRS[1])
        + " team-season against every " + str(PROBE_MODERN_PAIRS[0]) + "-" + str(PROBE_MODERN_PAIRS[1])
        + " team-season (" + f"{len(older_idx) * len(modern_idx):,}" + " pairs), full-season profiles, "
        "neutral court as the export computes it. For the league-relative probe a completed season is "
        "measured against its own league. \"Matched quality\" keeps the " + f"{int(matched.sum()):,}"
        + " pairs whose season net ratings are within 1 point: a model with no era preference "
        "should give those about 50%.\n\n"
        + md_table(["Model", "Mean P(older team wins)", "Older team favoured", "Matched quality: mean P(older)"], pair_rows),
    ])
    return text, key



def build_older_matchups(allowed_ids: set) -> pd.DataFrame:
    games = load_games(FIRST_SEASON, allowed_ids)
    games = games[games["season"] <= LAST_OLDER_SEASON]
    stats = load_team_games(FIRST_SEASON, allowed_ids)
    stats = stats[stats["season"] <= LAST_OLDER_SEASON]
    out = attach_point_in_time_profiles(games, stats)
    out = out.sort_values(["season", "game_date"]).reset_index(drop=True)
    if out.empty or out["game_id"].duplicated().any():
        raise ValueError("Older-season matchup rows are empty or have duplicate game_ids.")
    return out


def build_formula_1997(allowed_ids: set) -> pd.DataFrame:
    """1996-97 games rebuilt with box-score formulas instead of the NBA's values."""
    games = load_games(LAST_OLDER_SEASON, allowed_ids)
    games = games[games["season"] == LAST_OLDER_SEASON]
    basic = _read_team_games(BASIC_STATS_PATH)
    basic = basic[basic["season"] == LAST_OLDER_SEASON]
    basic = compute_box_score_advanced(basic)
    basic[UNMATCHED_FORMULA_COLS] = np.nan     # as load_team_games treats older seasons
    basic = basic[basic["teamId"].isin(allowed_ids)]
    return attach_point_in_time_profiles(games, basic)


def score(df: pd.DataFrame, release) -> pd.DataFrame:
    """Home-win probability from the release, built the way predict_matchup builds its row."""
    data = {}
    for col in release.columns:
        if col.startswith("home_") or col.startswith("away_"):
            data[col] = df[col].to_numpy(dtype=float)
        elif col.endswith("_diff"):
            base = col[:-5]
            data[col] = df["home_" + base].to_numpy(dtype=float) - df["away_" + base].to_numpy(dtype=float)
        else:
            raise ValueError("Unrecognized model column: " + col)
    X = pd.DataFrame(data, columns=release.columns)
    classes = list(release.classifier.classes_)
    out = df[["game_id", "season", "game_type", "home_win", "home_team_id", "away_team_id",
              "home_regular_games_played", "away_regular_games_played",
              "home_regular_win_pct", "away_regular_win_pct"]].copy()
    out["p_home"] = release.classifier.predict_proba(X)[:, classes.index(1)]
    return out


def metrics(s: pd.DataFrame) -> dict:
    y, p = s["home_win"].to_numpy(), np.clip(s["p_home"].to_numpy(), 1e-15, 1 - 1e-15)
    better = np.where(s["home_regular_win_pct"] >= s["away_regular_win_pct"], 1, 0)
    return {
        "n":        len(s),
        "accuracy": float(((p >= 0.5).astype(int) == y).mean()),
        "log_loss": float(-(y * np.log(p) + (1 - y) * np.log(1 - p)).mean()),
        "brier":    float(((p - y) ** 2).mean()),
        "home":     float(y.mean()),
        "better":   float((better == y).mean()),
    }


def metric_row(label: str, s: pd.DataFrame) -> list:
    if s.empty:
        return [label, "0", "", "", "", "", ""]
    m = metrics(s)
    return [label, f"{m['n']:,}", fmt(m["accuracy"] * 100, 1) + "%", fmt(m["log_loss"], 4), fmt(m["brier"], 4),
            fmt(m["home"] * 100, 1) + "%", fmt(m["better"] * 100, 1) + "%"]


METRIC_HEADERS = ["Games", "n", "Accuracy", "Log loss", "Brier", "Home team wins", "Better record wins"]


def calibration_table(s: pd.DataFrame) -> list:
    bins = pd.cut(s["p_home"], CALIBRATION_BINS, include_lowest=True)
    rows = []
    for interval, g in s.groupby(bins, observed=True):
        rows.append([f"{max(interval.left, 0):.1f}-{interval.right:.1f}", f"{len(g):,}",
                     fmt(g["p_home"].mean() * 100, 1) + "%", fmt(g["home_win"].mean() * 100, 1) + "%"])
    return rows


def backtest_section(scored: pd.DataFrame, formula_1997: pd.DataFrame, nba_1997: pd.DataFrame,
                     release, dropped: dict) -> tuple[str, dict]:
    summary_rows, type_rows = [], []
    for label, lo, hi in PERIODS:
        p = scored[(scored["season"] >= lo) & (scored["season"] <= hi)]
        summary_rows.append(metric_row(label, p))
        for gt in (GAME_TYPE_REGULAR, GAME_TYPE_PLAYOFF):
            type_rows.append(metric_row(label + ", " + gt.lower(), p[p["game_type"] == gt]))
        reg = p[p["game_type"] == GAME_TYPE_REGULAR]
        settled = reg[(reg["home_regular_games_played"] >= 20) & (reg["away_regular_games_played"] >= 20)]
        type_rows.append(metric_row(label + ", regular season after 20 games", settled))

    season_rows = []
    for season, g in scored.groupby("season"):
        r = metric_row(str(season), g)
        r.insert(2, f"{int((g['game_type'] == GAME_TYPE_PLAYOFF).sum()):,}")
        season_rows.append(r)

    older = scored[scored["season"] <= LAST_OLDER_SEASON]
    test  = scored[scored["season"] >= 2022]
    calib = []
    for label, s in (("1986-1997", older), ("2022-2026 (test)", test),
                     ("1986-1997 playoffs", older[older["game_type"] == GAME_TYPE_PLAYOFF]),
                     ("2022-2026 playoffs", test[test["game_type"] == GAME_TYPE_PLAYOFF])):
        calib.append("**" + label + "**\n\n" + md_table(["Predicted home win", "Games", "Mean predicted", "Home won"],
                                                         calibration_table(s)))

    # 1996-97 twice: NBA values vs box-score formulas
    both = nba_1997.merge(formula_1997[["game_id", "p_home"]], on="game_id", suffixes=("", "_formula"))
    delta = (both["p_home_formula"] - both["p_home"]).abs()
    flips = int(((both["p_home"] >= 0.5) != (both["p_home_formula"] >= 0.5)).sum())
    f97 = both.drop(columns="p_home").rename(columns={"p_home_formula": "p_home"})

    key = {
        "older":    metrics(older),
        "older_po": metrics(older[older["game_type"] == GAME_TYPE_PLAYOFF]),
        "test":     metrics(test),
        "test_po":  metrics(test[test["game_type"] == GAME_TYPE_PLAYOFF]),
        "val":      metrics(scored[(scored["season"] >= 2019) & (scored["season"] <= 2021)]),
        "delta_mean": float(delta.mean()), "delta_max": float(delta.max()), "flips": flips, "n97": len(both),
    }

    text = "\n\n".join([
        "Release scored: `" + release.version + "` (" + str(len(release.columns)) + " columns, trained on "
        "playoff games through " + str(release.manifest.get("trainedThroughSeason")) + "). Each game is scored "
        "with the real home and away sides, from point-in-time profiles: only games that tipped off "
        "earlier that season, ordered by `gameDateTimeEst`, exactly as `build_matchup_training_data.py` "
        "builds them. A game is scored when both teams have played at least one regular-season game "
        "that season (" + f"{dropped['older']:,}" + " opening games dropped in 1986-1997, "
        + f"{dropped['modern']:,}" + " from 1998 on). \"Better record wins\" picks the team with the "
        "higher season-to-date win percentage (home team on a tie); it is a baseline, not the model.",
        "The 1998-2018 rows are the seasons `hist-v1` trained on, with leaky features at the time, so "
        "they flatter it and are shown only for reference. The honest comparison for 1986-1997 is "
        "the validation and test seasons.",
        "### Summary\n\n" + md_table(METRIC_HEADERS, summary_rows),
        "### Regular season and playoffs\n\n" + md_table(METRIC_HEADERS, type_rows),
        "### By season\n\n" + md_table(["Season", "n", "Playoff games"] + METRIC_HEADERS[2:], season_rows),
        "### Calibration\n\n" + "\n\n".join(calib),
        "### 1996-97 with the NBA's values versus the box-score formulas\n\n"
        "1996-97 is the one season that is both out of sample and covered by the NBA's own advanced "
        "values, so it shows what the formulas alone do to the model's output. Same "
        + f"{len(both):,}" + " games, same model, profiles built from each source (rebound percentages "
        "left blank in the formula version, as they are for older seasons).\n\n"
        + md_table(METRIC_HEADERS, [metric_row("1996-97, NBA values", nba_1997.merge(both[["game_id"]], on="game_id")),
                                    metric_row("1996-97, box-score formulas", f97)])
        + "\n\nMean absolute change in the home-win probability: " + fmt(delta.mean() * 100, 2)
        + " points (max " + fmt(delta.max() * 100, 2) + "). Picks that flip: " + str(flips) + " of "
        + f"{len(both):,}" + ".",
    ])
    return text, key



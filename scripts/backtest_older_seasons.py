def drift_section(stats: pd.DataFrame) -> str:
    reg = stats[stats["gameType"] == GAME_TYPE_REGULAR].copy()
    reg["three_rate"] = reg["threePointersAttempted"] / reg["fieldGoalsAttempted"]
    league = reg.groupby("season")[[c for _l, c, _d in DRIFT_STATS]].mean()
    modern = league.loc[2022:2026].mean()
    rows = []
    for season, r in league.iterrows():
        source = "box score" if season <= EXTENDED_STATS_START else "NBA"
        rows.append([str(season)] + [fmt(r[c], d) for _l, c, d in DRIFT_STATS] + [source])
    rows.append(["2022-2026 mean"] + [fmt(modern[c], d) for _l, c, d in DRIFT_STATS] + [""])
    return "\n\n".join([
        "League average per team-game, regular season. Ratings, pace and TS% for seasons before "
        "1996-97 come from the box-score formulas; from 1996-97 on they are the NBA's values. "
        "3PA rate is three-point attempts / field-goal attempts.",
        md_table(["Season"] + [l for l, _c, _d in DRIFT_STATS] + ["Source"], rows),
    ])


def season_label_checks(stats: pd.DataFrame) -> str:
    t = pd.to_datetime(stats["gameDateTimeEst"], format="mixed")
    older = stats[stats["season"] <= LAST_OLDER_SEASON]
    older_t = t[older.index]
    october_end = int(((older_t.dt.month == 10) & (older_t.dt.year == older["season"])).sum())
    bubble = stats[(t >= "2020-10-01") & (t < "2020-10-15") & (stats["gameType"] == GAME_TYPE_PLAYOFF)]
    return ("- Games from 1986-1997 played in October of the year their season ends: "
            + str(october_end) + ". Every older season starts in late October or November and ends by June.\n"
            "- 2020 playoff games played in October 2020 (the bubble Finals): " + str(bubble["gameId"].nunique()) + " games, labelled season "
            + ", ".join(str(s) for s in sorted(bubble["season"].unique())) + " by the `month < 10` rule. "
            "This is existing behaviour for every script, not new in F11; it moves those games into "
            "2020-21's playoff profiles, so 2020 and 2021 per-season figures should be read with that in mind.")



"""
backtest_older_seasons.py

F11 Session 1: can the served historical simulator score 1985-86 to 1996-97
teams honestly? Writes the evidence into reports/older_seasons_backtest.md.

1. Formula validation. For 1996-97 onward both the NBA's advanced values
   (TeamStatisticsExtended.csv) and the basic box score exist. Each
   BOX_SCORE_FORMULAS stat is computed from the box score and compared with
   the NBA's value per team-season.
2. Identity. Every 1986-97 team-season gets an era-correct, unique key
   (export_static_site_data.attach_identity raises on a duplicate).
3. Backtest. The active release never trained on 1986-97. It scores every
   1986-97 game from point-in-time (pre-game, cumulative) profiles built with
   build_matchup_training_data.attach_point_in_time_profiles, and the same
   metrics are computed on matchup_training_data.csv for its own seasons.
   The point-in-time rows are saved to data/processed/older_seasons_matchups.csv
   so src/models/test_pregame_leakage.py can check them.
4. Era drift. League-average offensive rating, pace, three-point attempt
   rate and true shooting for every season from 1986.
5. Era probe. Real games are always between two teams of the same season, so
   they cannot show cross-era bias. Two small probe models (not releases),
   trained alike on 1998-2018 point-in-time games, one on raw inputs and one
   on inputs relative to the league, are scored on real games and on every
   1987-97 versus 2022-26 neutral pairing; hist-v1 is scored on the same
   pairings.

Only the section below REPORT_MARKER is regenerated; the summary and
recommendation above it are written by hand and kept.

Run from repo root (after build_matchup_training_data.py):
    python scripts/backtest_older_seasons.py
"""


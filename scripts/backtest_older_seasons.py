def write_report(body: str) -> None:
    head = ("# Older seasons backtest (F11 Session 1)\n\n"
            "_Summary and recommendation to be written above the marker._\n\n")
    if REPORT_PATH.exists():
        existing = REPORT_PATH.read_text(encoding="utf-8")
        if REPORT_MARKER in existing:
            head = existing.split(REPORT_MARKER)[0]
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(head + REPORT_MARKER + "\n\n" + body + "\n", encoding="utf-8")


def main():
    allowed_ids = load_allowed_team_ids()
    release = load_active_release()
    print("Release: " + release.version)

    print("Validating box-score formulas against the NBA's values...")
    formula_text, verdicts = validate_formulas(allowed_ids)

    print("Building " + str(FIRST_SEASON) + "-2026 season profiles...")
    stats    = load_team_games(FIRST_SEASON, allowed_ids)
    profiles = build_season_profiles(stats)
    identity_text = identity_section(profiles)

    print("Building point-in-time rows for " + str(FIRST_SEASON) + "-" + str(LAST_OLDER_SEASON) + "...")
    older = build_older_matchups(allowed_ids)
    OLDER_PATH.parent.mkdir(parents=True, exist_ok=True)
    older.to_csv(OLDER_PATH, index=False)
    print("Older-season matchup rows: " + str(len(older)) + "  -> " + str(OLDER_PATH))

    modern = pd.read_csv(MATCHUP_PATH, low_memory=False)
    if modern["season"].min() <= LAST_OLDER_SEASON:
        raise ValueError("matchup_training_data.csv already holds seasons up to " + str(LAST_OLDER_SEASON)
                         + "; this backtest expects them only in " + OLDER_PATH.name)

    def scoreable(df):
        return df[(df["home_regular_games_played"] >= 1) & (df["away_regular_games_played"] >= 1)]

    older_ok, modern_ok = scoreable(older), scoreable(modern)
    dropped = {"older": len(older) - len(older_ok), "modern": len(modern) - len(modern_ok)}
    scored = pd.concat([score(older_ok, release), score(modern_ok, release)], ignore_index=True)

    nba_1997     = scored[scored["season"] == LAST_OLDER_SEASON]
    formula_1997 = score(scoreable(build_formula_1997(allowed_ids)), release)
    backtest_text, key = backtest_section(scored, formula_1997, nba_1997, release, dropped)

    print("Running the era probe...")
    probe_text, probe_key = era_probe_section(profiles, scoreable(older), modern_ok, release)

    body = "\n\n".join([
        "## Formula validation\n\n" + formula_text,
        "## Identity\n\n" + identity_text,
        "## Backtest of `" + release.version + "`\n\n" + backtest_text,
        "## Era drift\n\n" + drift_section(stats),
        "## Era probe\n\n" + probe_text,
        "## Season labels\n\n" + season_label_checks(stats),
    ])
    write_report(body)

    unusable = [k for k, ok in verdicts.items() if not ok]
    print("Formulas not usable: " + (", ".join(unusable) if unusable else "none"))
    for name in ("older", "older_po", "val", "test", "test_po"):
        m = key[name]
        print(f"  {name:9s} n={m['n']:6d}  acc={m['accuracy']:.4f}  logloss={m['log_loss']:.4f}  brier={m['brier']:.4f}")
    print(f"  1997 NBA vs formula: mean |dp|={key['delta_mean']:.4f}  max={key['delta_max']:.4f}  flips={key['flips']}/{key['n97']}")
    for name, p in probe_key.items():
        print(f"  matched-quality P(older wins), {name}: {p:.4f}")
    print("Report written to: " + str(REPORT_PATH))


if __name__ == "__main__":
    main()

"""
build_rag_worker_fixtures.py

Writes tests/fixtures/rag/worker_parity.json: what the Python reference does
on real inputs, so the Worker's TypeScript port (worker/src/ask/, F13 Session
5) can be held to it. worker/test/ask-parity.test.ts reads it. It holds:

    prompts     the system prompt, the regeneration prompt, the refusal text
    questions   for every eval question: the linker's result, the FTS5 query,
                and how many chunks survive the filters
    grounding   real model answers from the eval runs (every failing one, up
                to a limit, and a sample of passing ones), with the check's
                verdict and the stripped text
    context     for a sample of questions: tool facts and the user message

Run from repo root (needs only committed files):
    python scripts/build_rag_worker_fixtures.py
"""

import json
import sys
from pathlib import Path

_REPO_ROOT_FOR_IMPORTS = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT_FOR_IMPORTS) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT_FOR_IMPORTS))

from src.rag import grounding
from src.rag.generate import (REFUSAL_TEXT, REGENERATE, SYSTEM_PROMPT, prompt_text, select_chunks, sources_of,
                              tool_facts, user_message)
from src.rag.index_local import fts_query, load_corpus
from src.rag.linker import Linker
from src.rag.retrieve import allowed, constraints_for
from src.rag.tools import Tools

REPO_ROOT      = Path(__file__).resolve().parent.parent
QUESTIONS_PATH = REPO_ROOT / "tests" / "fixtures" / "rag" / "eval_questions.jsonl"
RUNS_DIR       = REPO_ROOT / "reports" / "rag_runs"
OUTPUT_PATH    = REPO_ROOT / "tests" / "fixtures" / "rag" / "worker_parity.json"

GROUNDING_RUNS = ["answer-llama8b-dev", "answer-llama8b-test", "answer-qwen3-dev", "answer-qwen3-test",
                  "answer-llama8b-nofacts-test", "answer-gemma4-dev", "answer-gemma4-test"]
MAX_FAILING = 120
MAX_PASSING = 80
CONTEXT_EVERY = 6    # every 6th question gets a full context case


def grounding_cases(chunks: dict) -> list[dict]:
    failing, passing = [], []
    for name in GROUNDING_RUNS:
        with open(RUNS_DIR / (name + ".json"), encoding="utf-8") as f:
            run = json.load(f)
        for row in run["questions"]:
            sources = sources_of(row["facts"], row["chunk_ids"], chunks)
            report = grounding.check(row["first_answer"], sources, row["question"])
            stripped, removed = grounding.strip_unsupported(report, sources)
            case = {
                "run": name, "id": row["id"], "question": row["question"], "answer": row["first_answer"],
                "facts": row["facts"], "chunk_ids": row["chunk_ids"], "ok": report.ok, "numbers": report.numbers,
                "citations": report.citations, "sentences": report.sentences,
                "problems": [[i, kind, msg] for i, _, msg, kind in report.problems],
                "stripped": stripped, "removed": removed, "feedback": grounding.feedback(report),
            }
            (passing if report.ok else failing).append(case)
    step = max(1, len(passing) // MAX_PASSING)
    return failing[:MAX_FAILING] + passing[::step][:MAX_PASSING]


def main():
    corpus = load_corpus()
    chunks = {c["id"]: c for c in corpus}
    linker = Linker.from_index()
    tools = Tools.from_files()
    with open(QUESTIONS_PATH, encoding="utf-8") as f:
        questions = [json.loads(line) for line in f]

    rows, contexts, opponents = [], [], {}
    for i, q in enumerate(questions):
        link = linker.link(q["question"])
        cons = constraints_for(link, q["context"])
        rows.append({"question": q["question"], "context": q["context"], "link": link.as_dict(),
                     "fts": fts_query(q["question"]), "constraint_keys": cons.keys,
                     "allowed": sum(allowed(c, cons) for c in corpus)})
        if i % CONTEXT_EVERY == 0:
            facts, covered = tool_facts(tools, link, q["context"])
            if len(covered) >= 2:
                a, b = covered[0], covered[1]
                opponents.setdefault(a, {})[b] = tools.opponents(a)[b]
            # A fixed ranking stands in for retrieval: the corpus order of the allowed chunks.
            ranked = [c["id"] for c in corpus if allowed(c, cons)][:20]
            chosen = select_chunks(ranked, chunks, covered, 5, False)
            contexts.append({"question": q["question"], "context": q["context"], "facts": facts, "covered": covered,
                             "ranked": ranked, "chosen": chosen,
                             "message": user_message(q["question"], facts, [prompt_text(chunks[c]) for c in chosen])})

    payload = {
        "about": "Generated by scripts/build_rag_worker_fixtures.py. The Worker's port must reproduce it.",
        "prompts": {"system": SYSTEM_PROMPT, "regenerate": REGENERATE, "refusal": REFUSAL_TEXT},
        "questions": rows,
        "grounding": grounding_cases(chunks),
        "context": contexts,
        "opponents": opponents,
    }
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    print("Questions: " + str(len(rows)) + "  Grounding cases: " + str(len(payload["grounding"]))
          + " (" + str(sum(not c["ok"] for c in payload["grounding"])) + " failing)  Context cases: " + str(len(contexts)))
    print("Saved " + str(OUTPUT_PATH))


if __name__ == "__main__":
    main()

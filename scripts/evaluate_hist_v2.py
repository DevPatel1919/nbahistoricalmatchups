def write_report(body: str) -> None:
    head = "# hist-v2 evaluation (F11 Phase A)\n\n_Summary to be written above the marker._\n\n"
    if REPORT_PATH.exists():
        existing = REPORT_PATH.read_text(encoding="utf-8")
        if REPORT_MARKER in existing:
            head = existing.split(REPORT_MARKER)[0]
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(head + REPORT_MARKER + "\n\n" + body + "\n", encoding="utf-8")


def main():
    new = load_release(RELEASES_DIR / NEW)
    old = load_release(RELEASES_DIR / OLD)
    print("Releases: " + new.version + " (" + str(len(new.columns)) + " columns), " + old.version)

    rows = pd.read_csv(HISTORICAL_PATH, low_memory=False)
    rows = rows[(rows["home_regular_games_played"] >= 1) & (rows["away_regular_games_played"] >= 1)].reset_index(drop=True)
    scored = {m.version: score(rows, m).assign(season=rows["season"].to_numpy()) for m in (new, old)}

    print("Building Phase B profiles (1986 on, game types filled)...")
    ids = load_allowed_team_ids()
    new_profiles = build_season_profiles(load_team_games(OLDER_ERA_START + 1, ids, fill_game_types=True))
    old_profiles = build_season_profiles(load_team_games(MODERN_ERA_START + 1, ids))
    served = attach_identity(add_own_season_relative_columns(new_profiles)).reset_index(drop=True)
    print("Phase B team-seasons: " + str(len(served)))

    print("Scoring every ordered pair with both releases...")
    N, NM = {}, {}
    for m in (new, old):
        N[m.version], NM[m.version] = neutral_matrix(served, m)

    fixes_text = data_fixes_section(old_profiles, new_profiles)
    games_text, key = real_games_section(rows, scored)
    cross_text, cross_key = cross_era_section(served, N)

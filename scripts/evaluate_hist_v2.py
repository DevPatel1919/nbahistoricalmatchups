def full_metrics(s: pd.DataFrame) -> dict:
    m = metrics(s)
    y = s["home_win"].to_numpy()
    m["roc_auc"] = float(roc_auc_score(y, s["p_home"])) if len(np.unique(y)) == 2 else np.nan
    return m


def pct(x) -> str:
    return fmt(x * 100, 1) + "%"


def settled(df: pd.DataFrame) -> pd.Series:
    return (df["home_regular_games_played"] >= SETTLED_GAMES) & (df["away_regular_games_played"] >= SETTLED_GAMES)


def neutral_matrix(profiles: pd.DataFrame, release) -> tuple[np.ndarray, np.ndarray]:
    """Neutral P(row team beats column team) and margin, exactly as the export rounds them."""
    P, M = score_all_ordered_pairs(profiles, release.classifier, release.regressor, release.columns)
    N  = np.round((P + (1 - P.T)) / 2, 4)
    NM = np.round((M - M.T) / 2, 1)
    np.fill_diagonal(N, np.nan)
    np.fill_diagonal(NM, np.nan)
    return N, NM


def pair_probability(profiles: pd.DataFrame, release, key_a: str, key_b: str) -> float:
    pair = profiles[profiles["key"].isin([key_a, key_b])].set_index("key").loc[[key_a, key_b]].reset_index()
    P, _M = score_all_ordered_pairs(pair, release.classifier, release.regressor, release.columns)
    return round(float((P[0, 1] + (1 - P[1, 0])) / 2), 4)


def served_probability(key_a: str, key_b: str):
    path = SERVED_DIR / "teams" / (key_a + ".json")
    if not path.exists():
        return None
    return json.loads(path.read_text())["opponents"].get(key_b, {}).get("p")


def curated_entrants() -> list:
    text = CURATED_PATH.read_text(encoding="utf-8")
    block = text[text.index("entrants:"):]
    block = block[:block.index("]")]
    return re.findall(r'"(\d{4}-[a-z0-9-]+)"', block)



"""
evaluate_hist_v2.py

F11 Phase A: the evidence the owner decides hist-v2 on. Scores hist-v2 and
hist-v1 on the same point-in-time games (historical_training_data.csv), and
compares what each would serve, into reports/hist_v2_evaluation.md.

1. Data fixes. Blank game types per season (and what they were), and which
   served team-seasons the 2021-22 / 2000-01 fill and the October 2020 Finals
   rule change.
2. Real games. Accuracy, log loss, Brier and ROC-AUC on validation (2019-21)
   and test (2022-26), by game type, with "home team wins" and "better record
   wins" baselines; by season 1987-2026; calibration on the test seasons.
3. Cross-era check. Every 1987-97 team-season against every 2022-26 one,
   neutral court as the export computes it. Matched-quality pairs (season net
   ratings within 1 point) should come out near 50%.
4. Before and after. Neutral P(team A wins): hist-v1 as served today
   (frontend/public/data/teams/) against hist-v2 on the Phase B profiles
   (1986-2026, own-season z-scores), for named pairs and the Champions Bracket.
5. Top and bottom team-seasons by mean neutral win probability, the margin
   regressor's error, and the columns hist-v2 reads with their weights.

Only the section below REPORT_MARKER is regenerated; the summary above it is
written by hand and kept.

Run from repo root (after build_historical_training_data.py, training, and
promote_release.py --build hist-v2):
    python scripts/evaluate_hist_v2.py
"""


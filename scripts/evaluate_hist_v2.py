def real_games_section(rows: pd.DataFrame, scored: dict) -> tuple[str, dict]:
    headers = ["Games", "Model", "n", "Accuracy", "Log loss", "Brier", "ROC-AUC", "Home team wins", "Better record wins"]
    table, key = [], {}
    for label, lo, hi in PERIODS:
        for part, mask_fn in (("all", lambda d: d["season"] > 0),
                              ("both teams 20+ games", settled),
                              ("regular season", lambda d: d["game_type"] == GAME_TYPE_REGULAR),
                              ("playoffs", lambda d: d["game_type"] == GAME_TYPE_PLAYOFF)):
            for model in (NEW, OLD):
                s = scored[model]
                s = s[(s["season"] >= lo) & (s["season"] <= hi)]
                s = s[mask_fn(s)]
                m = full_metrics(s)
                key[(label, part, model)] = m
                table.append([label + ", " + part, "`" + model + "`", f"{m['n']:,}", pct(m["accuracy"]),
                              fmt(m["log_loss"], 4), fmt(m["brier"], 4), fmt(m["roc_auc"], 3),
                              pct(m["home"]), pct(m["better"])])

    season_rows = []
    for season in sorted(rows["season"].unique()):
        n = scored[NEW][scored[NEW]["season"] == season]
        o = scored[OLD][scored[OLD]["season"] == season]
        mn, mo = metrics(n), metrics(o)
        season_rows.append([str(season), f"{mn['n']:,}", f"{int((n['game_type'] == GAME_TYPE_PLAYOFF).sum()):,}",
                            pct(mn["accuracy"]), fmt(mn["log_loss"], 4), pct(mo["accuracy"]), fmt(mo["log_loss"], 4),
                            pct(mn["better"])])

    calib = []
    for model in (NEW, OLD):
        t = scored[model][scored[model]["season"] >= 2022]
        calib.append("**`" + model + "`, test seasons 2022-2026**\n\n"
                     + md_table(["Predicted home win", "Games", "Mean predicted", "Home won"], calibration_table(t)))
        po = t[t["game_type"] == GAME_TYPE_PLAYOFF]
        calib.append("**`" + model + "`, test-season playoffs**\n\n"
                     + md_table(["Predicted home win", "Games", "Mean predicted", "Home won"], calibration_table(po)))

    text = "\n\n".join([
        "Both releases score the same rows: every game in `historical_training_data.csv` (point-in-time "
        "profiles, playoff games in the calendar year they were played, 2001 and 2022 game types filled) "
        "in which both teams had played at least one regular-season game. Each game is scored with its real "
        "home and away sides. `hist-v1` reads the raw stats; `hist-v2` reads them as z-scores against the "
        "previous season. \"Better record wins\" picks the higher season-to-date win percentage (home on a "
        "tie). `hist-v2` was chosen on the \"both teams 20+ games\" validation rows; test was scored once.",
        md_table(headers, table),
        "### By season\n\n" + md_table(["Season", "n", "Playoff games", "hist-v2 accuracy", "hist-v2 log loss",
                                         "hist-v1 accuracy", "hist-v1 log loss", "Better record wins"], season_rows),
        "### Calibration\n\n" + "\n\n".join(calib),
    ])
    return text, key



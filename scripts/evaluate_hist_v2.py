def data_fixes_section(old_profiles: pd.DataFrame, new_profiles: pd.DataFrame) -> str:
    games = pd.read_csv(GAMES_TABLE_PATH, usecols=["gameId", "gameType"], low_memory=False).drop_duplicates("gameId")
    rows = []
    for path in (STATS_PATH, BASIC_STATS_PATH):
        s = pd.read_csv(path, usecols=["gameId", "gameDateTimeEst", "gameType"], low_memory=False)
        t = pd.to_datetime(s["gameDateTimeEst"], format="mixed")
        s["season"] = t.dt.year.where(t.dt.month < 10, t.dt.year + 1)
        blank = s[s["gameType"].isna()].merge(games.rename(columns={"gameType": "games_csv"}), on="gameId", how="left")
        blank["counted"] = game_id_prefix(blank["gameId"]).isin(GAME_ID_PREFIX_TYPES)
        for season, g in blank.groupby("season"):
            kinds = g["games_csv"].fillna("none").value_counts()
            rows.append([path.name, str(season), f"{len(g):,}", f"{int(g['counted'].sum()):,}",
                         ", ".join(k + " " + f"{v:,}" for k, v in kinds.items())])

    # Which served (1998 on) team-seasons change
    key = ["team_id", "season"]
    old = old_profiles.set_index(key)
    new = new_profiles[new_profiles["season"] > MODERN_ERA_START].set_index(key)
    added = new.index.difference(old.index)
    both  = new.index.intersection(old.index)
    num = [c for c in old.columns if c in new.columns and pd.api.types.is_numeric_dtype(old[c])]
    a, b = old.loc[both, num], new.loc[both, num]
    changed = ((a - b).abs() > 1e-9) | (a.isna() != b.isna())
    reg_changed = changed[[c for c in num if c.startswith("regular_")]].any(axis=1)
    po_changed  = changed[[c for c in num if c.startswith("playoff_")]].any(axis=1)
    change_rows = []
    for idx in both[reg_changed | po_changed]:
        n = new.loc[idx]
        o = old.loc[idx]
        what = []
        if reg_changed.loc[idx]:
            what.append("regular season " + str(int(o["regular_games_played"])) + " -> " + str(int(n["regular_games_played"])) + " games")
        if po_changed.loc[idx]:
            what.append("playoffs " + str(int(o["playoff_games_played"])) + " -> " + str(int(n["playoff_games_played"])) + " games")
        change_rows.append([str(idx[1]), n["team_city"] + " " + n["team_name"], "; ".join(what)])
    by_season = pd.Series([r[0] for r in change_rows]).value_counts().sort_index()

    finals = [r for r in change_rows if r[0] in ("2020", "2021")]
    return "\n\n".join([
        "### Blank `gameType` rows in the raw team-game files\n\n"
        "Every script drops a row whose `gameType` is blank. `Games.csv` has a type for every game. "
        "hist-v2 fills a blank only for a counted type (game id prefix 2 regular season, 4 playoffs, "
        "5 play-in) and raises if one stays blank or disagrees with its id; preseason (prefix 1) and "
        "NBA Cup (prefix 6) rows stay out.",
        md_table(["File", "Season", "Blank rows", "Counted (filled)", "Type in Games.csv"], rows),
        "### Served team-seasons that change (Phase B)\n\n"
        + f"{len(added)}" + " team-seasons from 1998 on are added (all from 2022: "
        + ", ".join(sorted(str(s) for s in new.loc[added].reset_index()["season"].unique())) + "). "
        + f"{len(change_rows)}" + " already-served team-seasons get different stats: "
        + ", ".join(f"{s}: {n}" for s, n in by_season.items()) + ". "
        "The 2001 and 2022 rows gain the regular-season games their blank game types hid; "
        "2022's two served one-game teams (`2022-clippers` 1-0, `2022-lakers` 0-1) get full seasons. "
        "The October 2020 Finals move from 2021 to 2020:",
        md_table(["Season", "Team", "Change"], finals),
    ])


